export function renderToolIcon(iconName: string, className?: string, size = 20) {
  switch (iconName) {
    case 'code':
      return <CodeIcon size={size} className={className} />;
    case 'binary':
      return <BinaryIcon size={size} className={className} />;
    case 'hash':
      return <HashIcon size={size} className={className} />;
    case 'text':
      return <TextIcon size={size} className={className} />;
    case 'textCase':
      return <TextCaseIcon size={size} className={className} />;
    case 'image':
      return <ImageIcon size={size} className={className} />;
    case 'imageRotate':
      return <ImageRotateIcon size={size} className={className} />;
    case 'pdf':
      return <PdfIcon size={size} className={className} />;
    case 'pdfExport':
      return <PdfExportIcon size={size} className={className} />;
    case 'calculator':
      return <CalculatorIcon size={size} className={className} />;
    case 'ruler':
      return <RulerIcon size={size} className={className} />;
    default:
      return <ZapIcon size={size} className={className} />;
  }
}
